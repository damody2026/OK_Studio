fn bench(m: &mut Model, w: f64, back: bool, lod: usize) {
    m.legs(w * 0.8, 0.43, 0.43);
    m.slats(w, 0.58, 0.43, if lod == 0 { 9 } else { 5 });
    if back {
        for x in [-w * 0.42, w * 0.42] {
            m.b([x, 0.24, 0.45], [0.06, 0.06, 0.52], 1);
        }
        for k in 0..if lod == 2 { 1 } else { 3 } {
            m.b([0., 0.26, 0.62 + k as f64 * 0.12], [w, 0.045, 0.09], 0);
        }
    }
    m.b([0., -0.02, 0.48], [w * 0.85, 0.43, 0.055], 3);
}
fn table(m: &mut Model, w: f64, d: f64, h: f64) {
    m.legs(w * 0.8, d * 0.7, h);
    m.b([0., 0., h], [w, d, 0.065], 0);
}
fn shade(m: &mut Model, r: f64, h: f64, lod: usize) {
    m.c([0., 0., 0.], [0.65, 0.65, 0.08], 7);
    m.c([0., 0., 0.08], [0.065, 0.065, h], 1);
    let n = if lod == 2 { 6 } else { 12 };
    m.parts.push(Part {
        shape: 2,
        p: [0., 0., h - 0.34],
        s: [2. * r, 2. * r, 0.42],
        rot: 0.,
        tilt: 0.,
        mat: 3,
    });
    for k in 0..n {
        let a = k as f64 * std::f64::consts::TAU / n as f64;
        let b = (k + 1) as f64 * std::f64::consts::TAU / n as f64;
        let mid = (a + b) / 2.;
        m.beam(
            [0., 0., h - 0.09],
            [r * 0.94 * mid.cos(), r * 0.94 * mid.sin(), h - 0.40],
            0.025,
            1,
        );
    }
}
fn frame(m: &mut Model, w: f64, d: f64, h: f64, lod: usize) {
    for x in [-w / 2., w / 2.] {
        for y in [-d / 2., d / 2.] {
            m.b([x, y, 0.], [0.13, 0.13, h], 0);
        }
    }
    for y in [-d / 2., d / 2.] {
        m.b([0., y, h], [w + 0.3, 0.15, 0.17], 0);
    }
    let n = if lod == 2 { 4 } else { 10 };
    for k in 0..n {
        m.b(
            [-w / 2. + k as f64 * w / (n - 1) as f64, 0., h + 0.17],
            [0.08, d + 0.4, 0.12],
            0,
        );
    }
}
fn rack(m: &mut Model, w: f64, h: f64, n: usize) {
    m.legs(w, 0.5, h);
    for j in 0..n {
        m.b(
            [0., 0., 0.1 + j as f64 * h / n as f64],
            [w + 0.1, 0.65, 0.055],
            0,
        );
    }
}
